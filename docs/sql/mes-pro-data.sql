-- ----------------------------
-- 数据核对
-- ----------------------------
select 'pro_process'           t, count(1) c from pro_process where del_flag='0'
union all select 'pro_process_content',   count(1) from pro_process_content where del_flag='0'
union all select 'pro_route',             count(1) from pro_route where del_flag='0'
union all select 'pro_route_process',     count(1) from pro_route_process where del_flag='0'
union all select 'pro_route_product',     count(1) from pro_route_product where del_flag='0'
union all select 'pro_route_product_bom', count(1) from pro_route_product_bom where del_flag='0';

-- ----------------------------
-- 路线工序链核对（每行应能看到 工序 -> 下一道工序，末道 next 为空）
-- ----------------------------
select r.route_code, r.route_name, p.order_num, p.process_code, p.process_name,
       p.next_process_code, p.next_process_name, p.link_type,
       p.default_pre_time, p.default_suf_time, p.key_flag, p.is_check, p.color_code
from pro_route_process p
join pro_route r on r.route_id = p.route_id
where p.del_flag = '0'
order by r.route_code, p.order_num;

-- ----------------------------
-- 制程用料核对（产品 -> 工序 -> 用到的料）
-- 注意：产品制程是「产品 + 路线」两个维度，只用 route_id 关联会把同路线上
--       不同产品的用料混在一起显示，必须再按 product_id 对齐
--       （pro_route_product_bom.product_id = 产品的 md_item.item_id）
-- 工序序号取 pro_route_process.order_num（pro_process 没有 order_num 列）
-- ----------------------------
select r.route_code, i.item_code product_code, i.item_name product_name,
       rp.order_num, c.process_name,
       b.item_code material_code, b.item_name material_name,
       b.quantity, b.unit_of_measure
from pro_route_product_bom b
join pro_route r on r.route_id = b.route_id
join pro_route_product i on i.route_id = b.route_id and i.item_id = b.product_id
join pro_process c on c.process_id = b.process_id
join pro_route_process rp on rp.route_id = b.route_id and rp.process_id = b.process_id
where b.del_flag = '0'
order by r.route_code, i.item_code, rp.order_num, b.item_code;

-- ----------------------------
-- 用料汇总核对（每个产品在每道工序用了多少种料）
-- ----------------------------
select r.route_code, i.item_code, i.item_name,
       rp.order_num, c.process_name, count(1) material_kinds
from pro_route_product_bom b
join pro_route r on r.route_id = b.route_id
join pro_route_product i on i.route_id = b.route_id and i.item_id = b.product_id
join pro_process c on c.process_id = b.process_id
join pro_route_process rp on rp.route_id = b.route_id and rp.process_id = b.process_id
where b.del_flag = '0'
group by r.route_code, i.item_code, i.item_name, rp.order_num, c.process_name
order by r.route_code, i.item_code, rp.order_num;

